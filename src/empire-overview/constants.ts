/**
 * Fall back to English for any language without its own table.
 *
 * `LanguageData` only ever had an `en` entry, and the original script was
 * pinned to four `-en` worlds by its `@include` lines, so nothing else could
 * reach it. Two things changed that: the include now covers every world on
 * every portal, and the settings panel offers a language dropdown whose
 * `selection` list is far longer than the table. Either route produced
 * `LanguageData[lang] === undefined`, and every one of the ~40 call sites
 * reads a property straight off it — so the board threw while drawing instead
 * of simply showing English labels.
 *
 * A proxy is used rather than patching the call sites because the value can
 * also come from storage, i.e. from a choice made in an earlier session.
 */
Constant.LanguageData = new Proxy(Constant.LanguageData, {
  get(table, key) {
    return key in table ? table[key] : table.en;
  },
});
